// 병합: 각 언어는 영어 기본값 + 오버라이드
function buildStrings(overrides: PartialStrings): Strings {
  return { ...DEF, ...overrides } as Strings;
}

export const STRINGS: Record<Locale, Strings> = {
  en: DEF as Strings,
  ko: buildStrings(OVERRIDES.ko),
  ja: buildStrings(OVERRIDES.ja),
  zh: buildStrings(OVERRIDES.zh),
  fr: buildStrings(OVERRIDES.fr),
  de: buildStrings(OVERRIDES.de),
  es: buildStrings(OVERRIDES.es),
  pt: buildStrings(OVERRIDES.pt),
  ru: buildStrings(OVERRIDES.ru),
  ar: buildStrings(OVERRIDES.ar),
  it: buildStrings(OVERRIDES.it),
  nl: buildStrings(OVERRIDES.nl),
  tr: buildStrings(OVERRIDES.tr),
  vi: buildStrings(OVERRIDES.vi),
  th: buildStrings(OVERRIDES.th),
};

export function t(locale: Locale, key: StringKey, n?: number): string {
  const val = (STRINGS[locale] ?? STRINGS.en)[key];
  if (typeof val === "function") return val(n ?? 0);
  return val as string;
}

/** navigator.language → Locale 변환 */
export function browserLangToLocale(lang: string): Locale {
  const base = lang.split("-")[0].toLowerCase();
  const map: Record<string, Locale> = {
    ko: "ko", ja: "ja", zh: "zh", fr: "fr", de: "de",
    es: "es", pt: "pt", ru: "ru", ar: "ar", it: "it",
    nl: "nl", tr: "tr", vi: "vi", th: "th",
  };
  return map[base] ?? "en";
}
